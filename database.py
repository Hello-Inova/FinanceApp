def criar_admin_inicial():
    email = os.getenv("ADMIN_EMAIL", "").strip().lower()
    senha = os.getenv("ADMIN_PASSWORD", "")
    nome = os.getenv("ADMIN_NAME", "Administrador").strip()
    if not email or not senha:
        return

    conn = conectar()
    cursor = conn.cursor()
    try:
        command = "INSERT INTO" if conn.postgres else "INSERT OR IGNORE INTO"
        suffix = " ON CONFLICT (email) DO NOTHING" if conn.postgres else ""
        cursor.execute(
            f"{command} usuarios "
            "(nome, cpf, email, senha, perfil, must_change_password) "
            "VALUES (?, ?, ?, ?, ?, ?)" + suffix,
            (nome, None, email, generate_password_hash(senha), "Administrativo", 1),
        )
        cursor.execute("SELECT id, senha FROM usuarios WHERE email = ?", (email,))
        existente = cursor.fetchone()
        if existente and check_password_hash(existente["senha"], senha):
            cursor.execute(
                "UPDATE usuarios SET must_change_password = 1 WHERE id = ?",
                (existente["id"],),
            )
        conn.commit()
    finally:
        conn.close()


def buscar_usuario(email, senha):
    conn = conectar()
    cursor = conn.cursor()
    cursor.execute(
        "SELECT id, nome, email, senha, perfil, ativo, session_version, "
        "must_change_password FROM usuarios WHERE email = ?",
        (email.strip().lower(),),
    )
    usuario = cursor.fetchone()
    conn.close()
    if not usuario or usuario["ativo"] != 1:
        return None
    if not check_password_hash(usuario["senha"], senha):
        return None
    usuario.pop("senha", None)
    return usuario


