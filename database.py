def finalizar_cadastro(token, nome, email, senha):
    conn = conectar()
    cursor = conn.cursor()
    try:
        lock = " FOR UPDATE" if conn.postgres else ""
        cursor.execute(
            "SELECT cpf, email, status, usuario_criado FROM solicitacoes_cadastro "
            "WHERE public_token = ?" + lock,
            (token,),
        )
        solicitacao = cursor.fetchone()
        if not solicitacao:
            return "nao_encontrada"
        if solicitacao["status"] != "pago":
            return "nao_pago"
        if solicitacao["usuario_criado"] == 1:
            return "ja_criado"
        if solicitacao["email"].lower() != email.lower():
            return "email_invalido"

        cursor.execute(
            "INSERT INTO usuarios (nome, cpf, email, senha, perfil) "
            "VALUES (?, ?, ?, ?, ?)",
            (
                nome,
                solicitacao["cpf"],
                email.lower(),
                generate_password_hash(senha),
                "Padrão",
            ),
        )
        cursor.execute(
            "UPDATE solicitacoes_cadastro SET usuario_criado = 1, "
            "atualizado_em = CURRENT_TIMESTAMP WHERE public_token = ?",
            (token,),
        )
        conn.commit()
        return "ok"
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def rate_limit_permitir(chave, limite, janela_segundos):
    agora = int(time.time())
    conn = conectar()
    cursor = conn.cursor()
    try:
        cursor.execute(
            "INSERT INTO rate_limits(chave, tentativas, janela_inicio) "
            "VALUES (?, 1, ?) ON CONFLICT(chave) DO UPDATE SET "
            "tentativas = CASE WHEN ? - rate_limits.janela_inicio >= ? "
            "THEN 1 ELSE rate_limits.tentativas + 1 END, "
            "janela_inicio = CASE WHEN ? - rate_limits.janela_inicio >= ? "
            "THEN ? ELSE rate_limits.janela_inicio END "
            "RETURNING tentativas",
            (chave, agora, agora, janela_segundos, agora, janela_segundos, agora),
        )
        row = cursor.fetchone()
        cursor.execute(
            "DELETE FROM rate_limits WHERE janela_inicio < ?",
            (agora - 7 * 24 * 60 * 60,),
        )
        conn.commit()
        return int(row["tentativas"]) <= limite
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


