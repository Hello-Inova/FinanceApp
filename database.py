def alterar_senha_propria(usuario_id, senha_atual, nova_senha):
    conn = conectar()
    cursor = conn.cursor()
    cursor.execute(
        "SELECT senha, session_version FROM usuarios WHERE id = ? AND ativo = 1",
        (usuario_id,),
    )
    usuario = cursor.fetchone()
    if not usuario or not check_password_hash(usuario["senha"], senha_atual):
        conn.close()
        return None
    nova_versao = int(usuario["session_version"]) + 1
    cursor.execute(
        "UPDATE usuarios SET senha = ?, must_change_password = 0, "
        "session_version = ? WHERE id = ?",
        (generate_password_hash(nova_senha), nova_versao, usuario_id),
    )
    conn.commit()
    conn.close()
    return nova_versao


