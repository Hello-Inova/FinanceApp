def criar_tabelas():

    conn = conectar()
    cursor = conn.cursor()

    id_column = (
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if DATABASE_URL
        else "INTEGER PRIMARY KEY AUTOINCREMENT"
    )

    cursor.execute(f"""
        CREATE TABLE IF NOT EXISTS usuarios (
            id {id_column},
            nome TEXT NOT NULL,
            cpf TEXT UNIQUE,
            email TEXT NOT NULL UNIQUE,
            senha TEXT NOT NULL,
            perfil TEXT NOT NULL DEFAULT 'Padrão',
            ativo INTEGER NOT NULL DEFAULT 1
        )
    """)

    cursor.execute(f"""
        CREATE TABLE IF NOT EXISTS lancamentos (
            id {id_column},
            usuario_id INTEGER NOT NULL,
            data TEXT NOT NULL,
            tipo TEXT NOT NULL,
            descricao TEXT NOT NULL,
            valor REAL NOT NULL,
            obs TEXT,
            FOREIGN KEY(usuario_id)
            REFERENCES usuarios(id)
        )
    """)

    cursor.execute(f"""
        CREATE TABLE IF NOT EXISTS compras (
            id {id_column},
            usuario_id INTEGER NOT NULL,
            data TEXT NOT NULL,
            categoria TEXT NOT NULL,
            item TEXT NOT NULL,
            quantidade REAL NOT NULL,
            valor_unitario REAL NOT NULL,
            valor_total REAL NOT NULL,
            comprado INTEGER NOT NULL DEFAULT 0,
            obs TEXT,
            FOREIGN KEY(usuario_id)
            REFERENCES usuarios(id)
        )
    """)

    cursor.execute(f"""
        CREATE TABLE IF NOT EXISTS configuracoes (
            id {id_column},
            tipo_pix TEXT NOT NULL,
            chave_pix TEXT NOT NULL,
            nome_recebedor TEXT NOT NULL,
            banco TEXT NOT NULL,
            criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            atualizado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)

    cursor.execute(f"""
        CREATE TABLE IF NOT EXISTS solicitacoes_cadastro (
            id {id_column},
            cpf TEXT NOT NULL,
            email TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'pendente',
            usuario_criado INTEGER NOT NULL DEFAULT 0,
            criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            pago_em TIMESTAMP
        )
    """)

    conn.commit()
    conn.close()


def criar_admin_inicial():
    """Seed exactly one admin when production credentials are configured."""
    email = os.getenv("ADMIN_EMAIL", "").strip().lower()
    senha = os.getenv("ADMIN_PASSWORD", "")
    nome = os.getenv("ADMIN_NAME", "Administrador").strip()

    if not email or not senha:
        return

    senha_hash = generate_password_hash(senha)
    conn = conectar()
    cursor = conn.cursor()

    if DATABASE_URL:
        cursor.execute("""
            INSERT INTO usuarios (nome, cpf, email, senha, perfil)
            VALUES (?, ?, ?, ?, ?)
            ON CONFLICT (email) DO NOTHING
        """, (nome, None, email, senha_hash, "Administrativo"))
    else:
        cursor.execute("""
            INSERT OR IGNORE INTO usuarios (nome, cpf, email, senha, perfil)
            VALUES (?, ?, ?, ?, ?)
        """, (nome, None, email, senha_hash, "Administrativo"))

    conn.commit()
    conn.close()


