def _normalizar_valor(valor):
    if isinstance(valor, Decimal):
        return str(valor)
    if isinstance(valor, (date, datetime)):
        return valor.isoformat()
    return valor


def _normalizar_linha(linha):
    if linha is None:
        return None
    dados = dict(linha)
    return {chave: _normalizar_valor(valor) for chave, valor in dados.items()}


class CursorAdapter:
    def __init__(self, cursor, postgres=False):
        self._cursor = cursor
        self._postgres = postgres

    def execute(self, query, params=()):
        if self._postgres:
            query = query.replace("?", "%s")
            parametros = params
        else:
            parametros = tuple(_normalizar_valor(valor) for valor in params)
        self._cursor.execute(query, parametros)
        return self

    def executemany(self, query, params):
        if self._postgres:
            query = query.replace("?", "%s")
            parametros = params
        else:
            parametros = [
                tuple(_normalizar_valor(valor) for valor in linha) for linha in params
            ]
        self._cursor.executemany(query, parametros)
        return self

    def fetchone(self):
        return _normalizar_linha(self._cursor.fetchone())

    def fetchall(self):
        return [_normalizar_linha(row) for row in self._cursor.fetchall()]

    @property
    def rowcount(self):
        return self._cursor.rowcount

    @property
    def lastrowid(self):
        return getattr(self._cursor, "lastrowid", None)


class ConnectionAdapter:
    def __init__(self, connection, postgres=False):
        self._connection = connection
        self.postgres = postgres

    def cursor(self):
        return CursorAdapter(self._connection.cursor(), self.postgres)

    def commit(self):
        self._connection.commit()

    def rollback(self):
        self._connection.rollback()

    def close(self):
        self._connection.close()


def conectar():
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row

        connection = psycopg.connect(
            DATABASE_URL,
            row_factory=dict_row,
            connect_timeout=10,
        )
        return ConnectionAdapter(connection, postgres=True)

    connection = sqlite3.connect(DB_NAME, timeout=10)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    return ConnectionAdapter(connection)


def _colunas(cursor, tabela, postgres):
    if postgres:
        cursor.execute(
            "SELECT column_name FROM information_schema.columns "
            "WHERE table_schema = 'public' AND table_name = ?",
            (tabela,),
        )
        return {row["column_name"] for row in cursor.fetchall()}
    cursor.execute(f"PRAGMA table_info({tabela})")
    return {row["name"] for row in cursor.fetchall()}


def executar_migracoes():
    """Apply versioned, idempotent schema migrations on startup."""
    conn = conectar()
    cursor = conn.cursor()
    postgres = conn.postgres
    identity = (
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if postgres
        else "INTEGER PRIMARY KEY AUTOINCREMENT"
    )
    money = "NUMERIC(14,2)" if postgres else "NUMERIC"
    date_type = "DATE" if postgres else "TEXT"

    try:
        if postgres:
            cursor.execute("SELECT pg_advisory_xact_lock(184726391)")

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS schema_migrations (
                version INTEGER PRIMARY KEY,
                applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS usuarios (
                id {identity},
                nome TEXT NOT NULL,
                cpf TEXT UNIQUE,
                email TEXT NOT NULL UNIQUE,
                senha TEXT NOT NULL,
                perfil TEXT NOT NULL DEFAULT 'Padrão',
                ativo INTEGER NOT NULL DEFAULT 1,
                session_version INTEGER NOT NULL DEFAULT 1,
                must_change_password INTEGER NOT NULL DEFAULT 0,
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS lancamentos (
                id {identity},
                usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
                data {date_type} NOT NULL,
                tipo TEXT NOT NULL,
                descricao TEXT NOT NULL,
                valor {money} NOT NULL,
                obs TEXT,
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS compras (
                id {identity},
                usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
                data {date_type} NOT NULL,
                categoria TEXT NOT NULL,
                item TEXT NOT NULL,
                quantidade {money} NOT NULL,
                valor_unitario {money} NOT NULL,
                valor_total {money} NOT NULL,
                comprado INTEGER NOT NULL DEFAULT 0,
                obs TEXT,
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS configuracoes (
                id {identity},
                tipo_pix TEXT NOT NULL,
                chave_pix TEXT NOT NULL,
                nome_recebedor TEXT NOT NULL,
                banco TEXT NOT NULL,
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        cursor.execute(f"""
            CREATE TABLE IF NOT EXISTS solicitacoes_cadastro (
                id {identity},
                public_token TEXT UNIQUE,
                cpf TEXT NOT NULL,
                email TEXT NOT NULL,
                status TEXT NOT NULL DEFAULT 'pendente',
                usuario_criado INTEGER NOT NULL DEFAULT 0,
                valor_centavos INTEGER NOT NULL DEFAULT 0,
                external_payment_id TEXT UNIQUE,
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                pago_em TIMESTAMP
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS rate_limits (
                chave TEXT PRIMARY KEY,
                tentativas INTEGER NOT NULL,
                janela_inicio INTEGER NOT NULL
            )
        """)

        timestamp_addition = "TIMESTAMP DEFAULT CURRENT_TIMESTAMP" if postgres else "TIMESTAMP"
        additions = {
            "usuarios": {
                "session_version": "INTEGER NOT NULL DEFAULT 1",
                "must_change_password": "INTEGER NOT NULL DEFAULT 0",
                "criado_em": timestamp_addition,
            },
            "lancamentos": {"criado_em": timestamp_addition},
            "compras": {"criado_em": timestamp_addition},
            "solicitacoes_cadastro": {
                "public_token": "TEXT",
                "valor_centavos": "INTEGER NOT NULL DEFAULT 0",
                "external_payment_id": "TEXT",
                "atualizado_em": timestamp_addition,
            },
        }
        for tabela, colunas in additions.items():
            existentes = _colunas(cursor, tabela, postgres)
            for coluna, definicao in colunas.items():
                if coluna not in existentes:
                    cursor.execute(
                        f"ALTER TABLE {tabela} ADD COLUMN {coluna} {definicao}"
                    )

        cursor.execute(
            "SELECT id FROM solicitacoes_cadastro "
            "WHERE public_token IS NULL OR public_token = ''"
        )
        for row in cursor.fetchall():
            cursor.execute(
                "UPDATE solicitacoes_cadastro SET public_token = ? WHERE id = ?",
                (secrets.token_urlsafe(32), row["id"]),
            )

        cursor.execute("SELECT version FROM schema_migrations WHERE version = ?", (2,))
        migration_2_aplicada = cursor.fetchone() is not None
        if postgres and not migration_2_aplicada:
            cursor.execute(
                "ALTER TABLE lancamentos ALTER COLUMN valor TYPE NUMERIC(14,2) "
                "USING valor::numeric"
            )
            cursor.execute(
                "ALTER TABLE compras ALTER COLUMN quantidade TYPE NUMERIC(14,2) "
                "USING quantidade::numeric"
            )
            cursor.execute(
                "ALTER TABLE compras ALTER COLUMN valor_unitario TYPE NUMERIC(14,2) "
                "USING valor_unitario::numeric"
            )
            cursor.execute(
                "ALTER TABLE compras ALTER COLUMN valor_total TYPE NUMERIC(14,2) "
                "USING valor_total::numeric"
            )
        cursor.execute("SELECT version FROM schema_migrations WHERE version = ?", (3,))
        migration_3_aplicada = cursor.fetchone() is not None
        if postgres and not migration_3_aplicada:
            cursor.execute(
                "ALTER TABLE lancamentos ALTER COLUMN data TYPE DATE USING data::date"
            )
            cursor.execute(
                "ALTER TABLE compras ALTER COLUMN data TYPE DATE USING data::date"
            )

        cursor.execute(
            "CREATE UNIQUE INDEX IF NOT EXISTS idx_solicitacoes_public_token "
            "ON solicitacoes_cadastro(public_token)"
        )
        cursor.execute(
            "CREATE UNIQUE INDEX IF NOT EXISTS idx_solicitacoes_payment_id "
            "ON solicitacoes_cadastro(external_payment_id) "
            "WHERE external_payment_id IS NOT NULL"
        )

        cursor.execute(
            "CREATE INDEX IF NOT EXISTS idx_lancamentos_usuario_data "
            "ON lancamentos(usuario_id, data)"
        )
        cursor.execute(
            "CREATE INDEX IF NOT EXISTS idx_compras_usuario_data "
            "ON compras(usuario_id, data)"
        )
        cursor.execute(
            "CREATE INDEX IF NOT EXISTS idx_solicitacoes_status "
            "ON solicitacoes_cadastro(status)"
        )

        cursor.execute("SELECT version FROM schema_migrations WHERE version = ?", (4,))
        migration_4_aplicada = cursor.fetchone() is not None
        admin_email = os.getenv("ADMIN_EMAIL", "").strip().lower()
        admin_password = os.getenv("ADMIN_PASSWORD", "")
        if not migration_4_aplicada and admin_email and admin_password:
            cursor.execute(
                "UPDATE usuarios SET senha = ?, perfil = 'Administrativo', ativo = 1, "
                "must_change_password = 1, session_version = session_version + 1 "
                "WHERE email = ?",
                (generate_password_hash(admin_password), admin_email),
            )

        # Version 5 reapplies the one-time reset after correcting the production
        # secret. It remains idempotent and never runs again after being recorded.
        cursor.execute("SELECT version FROM schema_migrations WHERE version = ?", (5,))
        migration_5_aplicada = cursor.fetchone() is not None
        if not migration_5_aplicada and admin_email and admin_password:
            cursor.execute(
                "UPDATE usuarios SET senha = ?, perfil = 'Administrativo', ativo = 1, "
                "must_change_password = 1, session_version = session_version + 1 "
                "WHERE email = ?",
                (generate_password_hash(admin_password), admin_email),
            )
        cursor.execute(
            "INSERT INTO schema_migrations(version) VALUES (?) "
            "ON CONFLICT(version) DO NOTHING",
            (1,),
        )
        cursor.execute(
            "INSERT INTO schema_migrations(version) VALUES (?) "
            "ON CONFLICT(version) DO NOTHING",
            (2,),
        )
        cursor.execute(
            "INSERT INTO schema_migrations(version) VALUES (?) "
            "ON CONFLICT(version) DO NOTHING",
            (3,),
        )
        cursor.execute(
            "INSERT INTO schema_migrations(version) VALUES (?) "
            "ON CONFLICT(version) DO NOTHING",
            (4,),
        )
        cursor.execute(
            "INSERT INTO schema_migrations(version) VALUES (?) "
            "ON CONFLICT(version) DO NOTHING",
            (5,),
        )
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


