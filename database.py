def buscar_usuario(email, senha):

    conn = conectar()
    cursor = conn.cursor()

    cursor.execute("""
        SELECT id, nome, email, senha, perfil, ativo
        FROM usuarios
        WHERE email = ?
    """, (email,))

    usuario = cursor.fetchone()

    conn.close()

    if not usuario:
        return None

    if usuario["ativo"] != 1:
        return None

    if check_password_hash(usuario["senha"], senha):

        return {
            "id": usuario["id"],
            "nome": usuario["nome"],
            "email": usuario["email"],
            "perfil": usuario["perfil"],
            "ativo": usuario["ativo"]
        }

    return None


